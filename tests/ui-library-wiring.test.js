/**
 * tests/ui-library-wiring.test.js
 *
 * Wiring the BDB component + motion-icon library (npm @hybridlabor-api/ui-motion-library,
 * shadcn namespace @bdb) into the UI skills and the godmode-ui-ux agent:
 * - the routing line (project design system first, then the BDB library, then the
 *   verified registries in docs/sources.md; wording from 07b798dd) is present in the
 *   three source files, with the version-pinned
 *   unpkg registry entry (never @latest: unpkg caches @latest)
 * - every version-pinned unpkg URL for the package in the repo uses the same version
 * - phantom-reference check (network) only when AOS_TEST_NETWORK=1: the pinned npm
 *   package exists and the pinned unpkg entry answers 200
 */

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PIN = '0.1.0';
const PKG = '@hybridlabor-api/ui-motion-library';
const ENTRY = `https://unpkg.com/${PKG}@${PIN}/publish/registry/{name}.json`;

const SOURCES = [
    path.join(ROOT, 'skills', 'basic', 'godmode-ui-ux', 'SKILL.md'),
    path.join(ROOT, 'skills', 'global_config', 'bdbdesignpro', 'SKILL.md'),
    path.join(ROOT, 'agents', 'godmode-ui-ux.md'),
];

function readFile(p) {
    return fs.readFileSync(p, 'utf8');
}

test('the three UI skills/agent sources carry the routing line with the pinned URL and no @latest', () => {
    for (const file of SOURCES) {
        const text = readFile(file);
        assert.ok(text.includes(ENTRY), `${path.relative(ROOT, file)}: pinned unpkg entry present`);
        assert.ok(
            /project's own design system and sources file first/.test(text) &&
                /docs\/sources\.md/.test(text),
            `${path.relative(ROOT, file)}: routing line present`
        );
        assert.ok(!new RegExp(PKG.replace(/[/@.]/g, (c) => `\\${c}`) + '@latest').test(text),
            `${path.relative(ROOT, file)}: no @latest for ${PKG}`);
    }
});

test('routing line is in sync across the agent persona copies', () => {
    const copies = [
        path.join(ROOT, 'agents', 'godmode-ui-ux.md'),
        path.join(ROOT, '.claude', 'agents', 'godmode-ui-ux.md'),
        path.join(ROOT, '.opencode', 'agents', 'godmode-ui-ux.md'),
        path.join(ROOT, '.codex', 'agents', 'godmode-ui-ux.md'),
        path.join(ROOT, '.codex', 'agents', 'godmode-ui-ux.toml'),
    ];
    for (const file of copies) {
        assert.ok(fs.existsSync(file), `${file} exists`);
        assert.ok(readFile(file).includes(ENTRY), `${path.relative(ROOT, file)}: pinned URL present`);
        // The .toml is a metadata stub; its prompt is the .md beside it.
        if (file.endsWith('.md')) assert.ok(/project's own design system and sources file first/.test(readFile(file)),
            `${path.relative(ROOT, file)}: routing line present`);
    }
    assert.strictEqual(
        readFile(path.join(ROOT, 'agents', 'godmode-ui-ux.md')),
        readFile(path.join(ROOT, '.claude', 'agents', 'godmode-ui-ux.md')),
        'agents/ and .claude/agents/ personas stay byte-identical (agents-v5 convention)'
    );
});

test('every pinned unpkg URL for the package in the repo uses the same version', () => {
    const rx = /https:\/\/unpkg\.com\/@hybridlabor-api\/ui-motion-library(@\d+\.\d+\.\d+)?[/)]?/g;
    const skipDirs = new Set(['.git', 'node_modules', 'vendor', 'assets']);
    const found = [];
    const walk = (dir) => {
        let entries;
        try {
            entries = fs.readdirSync(dir, { withFileTypes: true });
        } catch {
            return;
        }
        for (const e of entries) {
            if (skipDirs.has(e.name)) continue;
            const p = path.join(dir, e.name);
            if (e.isDirectory()) walk(p);
            else {
                let text;
                try { text = fs.readFileSync(p, 'utf8'); } catch { continue; }
                for (const m of text.matchAll(rx)) {
                    found.push({ file: path.relative(ROOT, p), version: m[1] || '(unpinned)' });
                }
            }
        }
    };
    walk(ROOT);
    assert.ok(found.length > 0, 'found at least one pinned URL');
    const versions = new Set(found.map((f) => f.version));
    assert.deepStrictEqual(versions, new Set([`@${PIN}`]),
        `all unpkg pins for the package are ${PIN}: ${JSON.stringify(found)}`);
});

test('generated dispatcher manifests keep their hands-off status (regenerated, not edited for this wiring)', () => {
    // plugin manifests are regenerated by the dispatcher build step and must not
    // drift by hand; this wiring therefore ships no manifest edits.
    const manifest = path.join(ROOT, 'plugin.json');
    assert.ok(fs.existsSync(manifest), 'plugin.json exists (dispatcher-generated)');
});

test('phantom-reference check hits the network only when AOS_TEST_NETWORK=1', async (t) => {
    if (process.env.AOS_TEST_NETWORK !== '1') {
        t.skip('network check disabled: set AOS_TEST_NETWORK=1 to verify the pinned npm package and the unpkg registry entry');
        return;
    }
    const npmUrl = 'https://registry.npmjs.org/@hybridlabor-api%2Fui-motion-library/' + PIN;
    const res = await fetch(npmUrl);
    assert.strictEqual(res.status, 200, `npm registry has ${PKG}@${PIN}`);
    const unpkgUrl = ENTRY.replace('{name}', 'statuspill');
    const res2 = await fetch(unpkgUrl);
    assert.strictEqual(res2.status, 200, `unpkg registry entry statuspill.json answers 200 at ${unpkgUrl}`);
});
