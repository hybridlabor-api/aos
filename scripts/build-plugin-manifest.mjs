#!/usr/bin/env node

// Generates .claude-plugin/plugin.json, the plugin-root agents/ directory and the
// subfolder plugin plugins/bdb-aos/ (same manifest data + skills/agents symlinks
// into the repo root, so the marketplace install cache stays small).
//
// Claude Code resolves plugin components two different ways, and only one of
// them is obvious:
//
//   skills  -> the manifest's "skills" array, one entry per skill DIRECTORY.
//              No globs ("skills/*/*/" is rejected as "Path not found") and no
//              recursion (a category dir like ./skills/global_config resolves to
//              nothing, because it holds no SKILL.md of its own). Every skill
//              must therefore be named explicitly, or it silently ships nothing.
//   agents  -> convention only, <plugin-root>/agents/*.md. The manifest's
//              "agents" key is accepted by the schema and then ignored, so a
//              correct-looking path list there yields 0 agents and no warning.
//
// The AOS skills live at skills/<category>/<name>/SKILL.md, two levels deep, and
// the agent personas live at .claude/agents/ (referenced by .agents/nodes.json
// personaFile paths and regenerated by installer.js, so they cannot move). Both
// facts mean the plugin needs a generated layout, which is what this script is.
//
// Slash commands (/bdb-aos:<name>) come from plugin-commands.json: one commands/<name>.md
// per entry plus a "commands" array in both manifests. OpenCode gets flat hyphen names
// (.opencode/commands/bdb-aos-<name>.md, /bdb-aos-<name>) because a colon is invalid in
// Windows file names; bodies.opencode is optional and falls back to the claude body with
// /bdb-aos:<cmd> rewritten. AOS_PLUGIN_COMMANDS overrides the source path (tests only).
//
// Codex has no verified commands/ handling, so its entry points are generated wrapper
// SKILLS (plugins/bdb-aos-codex/skills/<cmd>/SKILL.md, invoked as $bdb-aos:<cmd>) in a real
// directory, because `codex plugin add` drops symlinks from the install copy. The plugin's
// .codex-plugin/plugin.json and .agents/plugins/marketplace.json point there.
// agy reads a plugin.json at the plugin root (/bdb-aos:<cmd>); bodies.codex / bodies.agy are
// optional, agy overrides land in agy-commands/ and are only wired when present.
//
// Usage: node scripts/build-plugin-manifest.mjs [--check]

import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, readlinkSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');

const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const repoUrl = pkg.repository?.url?.replace(/^git\+/, '').replace(/\.git$/, '') ??
  'https://github.com/hybridlabor-api/aos';

function walkSkills(dir, output = []) {
  if (!existsSync(dir)) return output;
  for (const item of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, item.name);
    if (item.isDirectory()) walkSkills(full, output);
    else if (item.name === 'SKILL.md') output.push(dirname(full));
  }
  return output;
}

const skillDirs = walkSkills(join(ROOT, 'skills')).sort();
if (skillDirs.length === 0) throw new Error('No skills found under skills/ — refusing to write an empty manifest');

const skills = skillDirs.map((dir) => `./${relative(ROOT, dir).split(/[\\/]/).join('/')}`);

const agentSrc = join(ROOT, '.claude', 'agents');
const agentDst = join(ROOT, 'agents');
const agentNames = existsSync(agentSrc)
  ? readdirSync(agentSrc).filter((name) => name.endsWith('.md')).sort()
  : [];

// The personas are the same 13 files the repo loads via .claude/agents/. They are
// copied rather than symlinked because validate --strict (the release gate)
// refuses a symlinked component directory, and a symlink is fragile once the
// plugin is cloned or downloaded on a platform that does not create them.
const drift = [];
if (!CHECK) mkdirSync(agentDst, { recursive: true });
for (const name of agentNames) {
  const want = readFileSync(join(agentSrc, name));
  const path = join(agentDst, name);
  if (!existsSync(path) || !readFileSync(path).equals(want)) {
    if (CHECK) drift.push(name);
    else {
      writeFileSync(path, want);
      console.log(`synced agents/${name}`);
    }
  }
}
if (!CHECK) {
  for (const name of readdirSync(agentDst)) {
    if (!agentNames.includes(name)) {
      rmSync(join(agentDst, name));
      console.log(`removed stale agents/${name}`);
    }
  }
}

const commandsSrc = process.env.AOS_PLUGIN_COMMANDS ?? join(ROOT, 'plugin-commands.json');
const commandDefs = JSON.parse(readFileSync(commandsSrc, 'utf8')).commands ?? {};
const skillNames = new Set(skillDirs.map((dir) => dir.split(/[\\/]/).pop()));
const commandErrors = [];
for (const [name, def] of Object.entries(commandDefs)) {
  if (!/^[a-z][a-z0-9-]*$/.test(name)) commandErrors.push(`${name}: invalid command name`);
  if (skillNames.has(name)) commandErrors.push(`${name}: collides with a skill of the same name`);
  if (!def.description?.trim()) commandErrors.push(`${name}: empty description`);
  if (!def.bodies?.claude?.trim()) commandErrors.push(`${name}: no body for claude`);
  for (const harness of ['opencode', 'codex', 'agy']) {
    if (def.bodies?.[harness] !== undefined && !def.bodies[harness].trim()) commandErrors.push(`${name}: empty body for ${harness}`);
  }
  for (const ref of def.skills ?? []) {
    const found = ref.endsWith('*')
      ? [...skillNames].some((n) => n.startsWith(ref.slice(0, -1)))
      : skillNames.has(ref);
    if (!found && def.pending === undefined) commandErrors.push(`${name}: unknown skill ${ref}`);
  }
}
if (commandErrors.length > 0) {
  console.error(`plugin-commands.json invalid:\n  ${commandErrors.join('\n  ')}`);
  process.exit(1);
}
const commandNames = Object.keys(commandDefs).sort();
const commandFiles = Object.fromEntries(commandNames.map((name) => [
  `${name}.md`,
  `---\ndescription: ${JSON.stringify(commandDefs[name].description)}\n---\n\n${commandDefs[name].bodies.claude.trim()}\n`,
]));
const commands = commandNames.map((name) => `./commands/${name}.md`);
const opencodeBody = (def) =>
  (def.bodies.opencode ?? def.bodies.claude.replace(/\/bdb-aos:([a-z][a-z0-9-]*)/g, '/bdb-aos-$1')).trim();
const opencodeFiles = Object.fromEntries(commandNames.map((name) => [
  `bdb-aos-${name}.md`,
  `---\ndescription: ${JSON.stringify(commandDefs[name].description)}\n---\n\n${opencodeBody(commandDefs[name])}\n`,
]));

// Codex has no per-user argument placeholder, so $ARGUMENTS becomes prose.
const codexBody = (def) =>
  (def.bodies.codex ?? def.bodies.claude
    .replace(/\/bdb-aos:([a-z][a-z0-9-]*)/g, '$$bdb-aos:$1')
    .replace(/\$ARGUMENTS/g, 'whatever the user wrote after the skill name')).trim();
const codexFiles = Object.fromEntries(commandNames.map((name) => [
  `${name}/SKILL.md`,
  `---\nname: ${name}\ndescription: ${JSON.stringify(`${commandDefs[name].description} Generated from plugin-commands.json; invoke as $bdb-aos:${name}.`)}\n---\n\n${codexBody(commandDefs[name])}\n`,
]));
const agyOverrides = commandNames.filter((name) => commandDefs[name].bodies.agy !== undefined);
const agyFiles = Object.fromEntries(agyOverrides.map((name) => [
  `${name}.md`,
  `---\ndescription: ${JSON.stringify(commandDefs[name].description)}\n---\n\n${commandDefs[name].bodies.agy.trim()}\n`,
]));
const agyCommands = commandNames.map((name) => `./${agyOverrides.includes(name) ? 'agy-commands' : 'commands'}/${name}.md`);

const manifest = {
  $schema: 'https://anthropic.com/claude-code/plugin.schema.json',
  name: 'bdb-aos',
  version: pkg.version,
  description:
    'Full BDB Agent OS suite: 200+ curated skills, 13 subagents and the startcycle pipelines for Claude Code. ' +
    'Gate hooks and MCP servers are installed by the AOS installer.',
  author: { name: 'Tim Rennings / Hybridlabor Global LLC', email: 'hybridlabor@gmail.com' },
  homepage: repoUrl,
  repository: repoUrl,
  license: 'Apache-2.0',
  keywords: ['skills', 'agent-os', 'cicd', 'multiagent', 'startcycle', 'bdb'],
  skills,
  commands,
};

const serialized = `${JSON.stringify(manifest, null, 2)}\n`;
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const codexManifest = {
  name: manifest.name,
  version: pkg.version,
  description: 'Full BDB Agent OS suite for Codex: command entry points ($bdb-aos:setup, $bdb-aos:init, ...) generated from plugin-commands.json.',
  author: manifest.author,
  homepage: repoUrl,
  repository: repoUrl,
  license: manifest.license,
  keywords: manifest.keywords,
  skills: './skills/',
  interface: {
    displayName: 'BDB Agent OS',
    shortDescription: 'AOS commands for setup, planning and pipelines',
    longDescription: 'Entry-point skills for the BDB Agent OS suite: invoke $bdb-aos:<command> to run setup, project init, planning and the startcycle pipelines.',
    developerName: 'Hybridlabor Global LLC',
    category: 'Developer Tools',
    capabilities: ['Interactive', 'Read', 'Write'],
    websiteURL: repoUrl,
    defaultPrompt: ['$bdb-aos:setup', '$bdb-aos:doctor'],
  },
};
const CODEX_ROOT = 'plugins/bdb-aos-codex';
const codexMarket = {
  name: 'bdb-aos',
  interface: { displayName: 'BDB Agent OS' },
  plugins: [{
    name: manifest.name,
    source: { source: 'local', path: `./${CODEX_ROOT}` },
    policy: { installation: 'AVAILABLE', authentication: 'ON_INSTALL' },
    category: 'Developer Tools',
  }],
};
const { $schema: _schema, ...agyBase } = manifest;
const agyManifest = { ...agyBase, commands: agyCommands };
const generated = {
  '.codex-plugin/plugin.json': json({ ...codexManifest, skills: `./${CODEX_ROOT}/skills/` }),
  [`${CODEX_ROOT}/.codex-plugin/plugin.json`]: json(codexManifest),
  '.agents/plugins/marketplace.json': json(codexMarket),
  'plugin.json': json(agyManifest),
  'plugins/bdb-aos/plugin.json': json(agyManifest),
  ...Object.fromEntries(Object.entries(codexFiles).map(([f, c]) => [`${CODEX_ROOT}/skills/${f}`, c])),
  ...Object.fromEntries(Object.entries(agyFiles).map(([f, c]) => [`agy-commands/${f}`, c])),
};
const ownedDirs = { [`${CODEX_ROOT}/skills`]: (e) => e.isDirectory(), 'agy-commands': (e) => e.isFile() };
const genDrift = Object.entries(generated)
  .filter(([file, want]) => !existsSync(join(ROOT, file)) || readFileSync(join(ROOT, file), 'utf8') !== want)
  .map(([file]) => file);
const genStale = Object.entries(ownedDirs).flatMap(([dir, owned]) =>
  existsSync(join(ROOT, dir))
    ? readdirSync(join(ROOT, dir), { withFileTypes: true }).filter(owned)
      .map((e) => `${dir}/${e.name}`)
      .filter((path) => !Object.keys(generated).some((file) => file === path || file.startsWith(`${path}/`)))
    : []);
const legacyCodexMarket = join(ROOT, '.codex-plugin', 'marketplace.json');

// Release-gate validation: every generated manifest parses, versions track package.json,
// Codex outputs never carry the field its validator rejects, referenced files exist.
function validateGenerated() {
  const problems = [];
  for (const file of Object.keys(generated)) {
    if (!file.endsWith('.json') || !existsSync(join(ROOT, file))) continue;
    let doc;
    try { doc = JSON.parse(readFileSync(join(ROOT, file), 'utf8')); } catch { problems.push(`${file}: does not parse`); continue; }
    if (file.endsWith('plugin.json') && doc.version !== pkg.version) problems.push(`${file}: version ${doc.version} != package.json ${pkg.version}`);
    const base = join(ROOT, dirname(file).replace(/\.codex-plugin$/, ''));
    if (file.endsWith('plugin.json') && file !== '.agents/plugins/marketplace.json') {
      for (const ref of [...(doc.commands ?? []), ...(Array.isArray(doc.skills) ? doc.skills : [])]) {
        const target = join(base, ref, ref.endsWith('.md') ? '' : 'SKILL.md');
        if (!existsSync(target)) problems.push(`${file}: missing ${ref}`);
      }
      if (typeof doc.skills === 'string' && !existsSync(join(base, doc.skills))) problems.push(`${file}: missing ${doc.skills}`);
    }
  }
  for (const file of Object.keys(generated)) {
    if (/^(plugins\/bdb-aos-codex\/|\.codex-plugin\/|\.agents\/plugins\/)/.test(file) &&
      existsSync(join(ROOT, file)) && readFileSync(join(ROOT, file), 'utf8').includes('disable-model-invocation')) {
      problems.push(`${file}: contains disable-model-invocation (rejected by Codex)`);
    }
  }
  return problems;
}
const SUBDIR = join(ROOT, 'plugins', 'bdb-aos');
// Both manifests come from the same data; the subfolder one resolves the same
// ./skills/... paths through its symlinks.
const targets = [
  join(ROOT, '.claude-plugin', 'plugin.json'),
  join(SUBDIR, '.claude-plugin', 'plugin.json'),
];
const stale = targets.filter((t) => !existsSync(t) || readFileSync(t, 'utf8') !== serialized);
const links = {
  skills: '../../skills',
  agents: '../../agents',
  commands: '../../commands',
  ...(agyOverrides.length > 0 ? { 'agy-commands': '../../agy-commands' } : {}),
};
const badLinks = Object.entries(links).filter(([name, to]) => {
  const path = join(SUBDIR, name);
  return !existsSync(path) || !lstatSync(path).isSymbolicLink() || readlinkSync(path) !== to;
});

// `claude plugin tag` refuses to cut a release unless plugin.json and the
// enclosing marketplace entry agree on the version, so the marketplace copy of
// the number is generated here too rather than hand-maintained.
const marketPath = join(ROOT, '.claude-plugin', 'marketplace.json');
const market = JSON.parse(readFileSync(marketPath, 'utf8'));
const entry = market.plugins?.find((plugin) => plugin.name === manifest.name);
if (!entry) throw new Error(`marketplace.json has no entry named ${manifest.name}`);
entry.version = pkg.version;
const marketSerialized = `${JSON.stringify(market, null, 2)}\n`;
const commandsDst = join(ROOT, 'commands');
const commandDrift = Object.entries(commandFiles)
  .filter(([file, want]) => !existsSync(join(commandsDst, file)) || readFileSync(join(commandsDst, file), 'utf8') !== want)
  .map(([file]) => file);
const staleCommandFiles = existsSync(commandsDst)
  ? readdirSync(commandsDst).filter((file) => !(file in commandFiles))
  : [];
const ocDst = join(ROOT, '.opencode', 'commands');
const ocOwned = (file) => /^bdb-aos-.+\.md$/.test(file);
const ocDrift = Object.entries(opencodeFiles)
  .filter(([file, want]) => !existsSync(join(ocDst, file)) || readFileSync(join(ocDst, file), 'utf8') !== want)
  .map(([file]) => file);
const ocStale = existsSync(ocDst) ? readdirSync(ocDst).filter((file) => ocOwned(file) && !(file in opencodeFiles)) : [];
const marketCurrent = readFileSync(marketPath, 'utf8');

if (CHECK) {
  if (stale.length > 0) {
    console.error(`plugin.json is out of date (${stale.map((t) => relative(ROOT, t)).join(', ')}) — run: node scripts/build-plugin-manifest.mjs`);
    process.exit(1);
  }
  if (badLinks.length > 0) {
    console.error(`plugins/bdb-aos symlinks missing or wrong (${badLinks.map(([n]) => n).join(', ')}) — run: node scripts/build-plugin-manifest.mjs`);
    process.exit(1);
  }
  if (marketCurrent !== marketSerialized) {
    console.error('marketplace.json version is out of date — run: node scripts/build-plugin-manifest.mjs');
    process.exit(1);
  }
  if (commandDrift.length > 0 || staleCommandFiles.length > 0) {
    console.error(`commands/ is out of date (${[...commandDrift, ...staleCommandFiles].join(', ')}) — run: node scripts/build-plugin-manifest.mjs`);
    process.exit(1);
  }
  if (ocDrift.length > 0 || ocStale.length > 0) {
    console.error(`.opencode/commands/ is out of date (${[...ocDrift, ...ocStale].join(', ')}) — run: node scripts/build-plugin-manifest.mjs`);
    process.exit(1);
  }
  if (genDrift.length > 0 || genStale.length > 0 || existsSync(legacyCodexMarket)) {
    console.error(`Codex/agy manifests are out of date (${[...genDrift, ...genStale, ...(existsSync(legacyCodexMarket) ? ['.codex-plugin/marketplace.json (legacy)'] : [])].join(', ')}) — run: node scripts/build-plugin-manifest.mjs`);
    process.exit(1);
  }
  const problems = validateGenerated();
  if (problems.length > 0) {
    console.error(`generated manifests invalid:\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  if (drift.length > 0) {
    console.error(`agents/ is out of date (${drift.join(', ')}) — run: node scripts/build-plugin-manifest.mjs`);
    process.exit(1);
  }
  console.log(`plugin manifests up to date: ${skills.length} skills, ${agentNames.length} agents, ${commandNames.length} commands (+ ${commandNames.length} OpenCode)`);
} else {
  mkdirSync(commandsDst, { recursive: true });
  for (const [file, content] of Object.entries(commandFiles)) writeFileSync(join(commandsDst, file), content);
  for (const file of staleCommandFiles) rmSync(join(commandsDst, file));
  mkdirSync(ocDst, { recursive: true });
  for (const [file, content] of Object.entries(opencodeFiles)) writeFileSync(join(ocDst, file), content);
  for (const file of ocStale) rmSync(join(ocDst, file));
  for (const t of targets) {
    mkdirSync(dirname(t), { recursive: true });
    writeFileSync(t, serialized);
  }
  for (const [file, content] of Object.entries(generated)) {
    mkdirSync(dirname(join(ROOT, file)), { recursive: true });
    writeFileSync(join(ROOT, file), content);
  }
  for (const path of genStale) rmSync(join(ROOT, path), { recursive: true });
  rmSync(legacyCodexMarket, { force: true });
  for (const [name, to] of badLinks) {
    rmSync(join(SUBDIR, name), { force: true });
    symlinkSync(to, join(SUBDIR, name));
  }
  writeFileSync(marketPath, marketSerialized);
  console.log(`Wrote 2 plugin.json files with ${skills.length} skills, ${agentNames.length} agents and ${commandNames.length} commands`);
}
