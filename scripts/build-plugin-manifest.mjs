#!/usr/bin/env node

// Generates .claude-plugin/plugin.json, the plugin-root agents/ directory and the
// subfolder plugin plugins/bdb-aos/ (same manifest data + skills/agents symlinks
// into the repo root, so the marketplace install cache stays small).
//
// Claude Code resolves plugin components two different ways, and only one of
// them is obvious:
//
//   skills  -> the manifest's "skills" array, one entry per skill DIRECTORY.
//              No globs ("skills/*/*/" is rejected as "Path not found") and no
//              recursion (a category dir like ./skills/global_config resolves to
//              nothing, because it holds no SKILL.md of its own). Every skill
//              must therefore be named explicitly, or it silently ships nothing.
//   agents  -> convention only, <plugin-root>/agents/*.md. The manifest's
//              "agents" key is accepted by the schema and then ignored, so a
//              correct-looking path list there yields 0 agents and no warning.
//
// The AOS skills live at skills/<category>/<name>/SKILL.md, two levels deep, and
// the agent personas live at .claude/agents/ (referenced by .agents/nodes.json
// personaFile paths and regenerated by installer.js, so they cannot move). Both
// facts mean the plugin needs a generated layout, which is what this script is.
//
// Usage: node scripts/build-plugin-manifest.mjs [--check]

import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, readlinkSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');

const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const repoUrl = pkg.repository?.url?.replace(/^git\+/, '').replace(/\.git$/, '') ??
  'https://github.com/hybridlabor-api/aos';

function walkSkills(dir, output = []) {
  if (!existsSync(dir)) return output;
  for (const item of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, item.name);
    if (item.isDirectory()) walkSkills(full, output);
    else if (item.name === 'SKILL.md') output.push(dirname(full));
  }
  return output;
}

const skillDirs = walkSkills(join(ROOT, 'skills')).sort();
if (skillDirs.length === 0) throw new Error('No skills found under skills/ — refusing to write an empty manifest');

const skills = skillDirs.map((dir) => `./${relative(ROOT, dir).split(/[\\/]/).join('/')}`);

const agentSrc = join(ROOT, '.claude', 'agents');
const agentDst = join(ROOT, 'agents');
const agentNames = existsSync(agentSrc)
  ? readdirSync(agentSrc).filter((name) => name.endsWith('.md')).sort()
  : [];

// The personas are the same 13 files the repo loads via .claude/agents/. They are
// copied rather than symlinked because validate --strict (the release gate)
// refuses a symlinked component directory, and a symlink is fragile once the
// plugin is cloned or downloaded on a platform that does not create them.
const drift = [];
if (!CHECK) mkdirSync(agentDst, { recursive: true });
for (const name of agentNames) {
  const want = readFileSync(join(agentSrc, name));
  const path = join(agentDst, name);
  if (!existsSync(path) || !readFileSync(path).equals(want)) {
    if (CHECK) drift.push(name);
    else {
      writeFileSync(path, want);
      console.log(`synced agents/${name}`);
    }
  }
}
if (!CHECK) {
  for (const name of readdirSync(agentDst)) {
    if (!agentNames.includes(name)) {
      rmSync(join(agentDst, name));
      console.log(`removed stale agents/${name}`);
    }
  }
}

const manifest = {
  $schema: 'https://anthropic.com/claude-code/plugin.schema.json',
  name: 'bdb-aos',
  version: pkg.version,
  description:
    'Full BDB Agent OS suite: 200+ curated skills, 13 subagents and the startcycle pipelines for Claude Code. ' +
    'Gate hooks and MCP servers are installed by the AOS installer.',
  author: { name: 'Tim Rennings / Hybridlabor Global LLC', email: 'hybridlabor@gmail.com' },
  homepage: repoUrl,
  repository: repoUrl,
  license: 'Apache-2.0',
  keywords: ['skills', 'agent-os', 'cicd', 'multiagent', 'startcycle', 'bdb'],
  skills,
};

const serialized = `${JSON.stringify(manifest, null, 2)}\n`;
const SUBDIR = join(ROOT, 'plugins', 'bdb-aos');
// Both manifests come from the same data; the subfolder one resolves the same
// ./skills/... paths through its symlinks.
const targets = [
  join(ROOT, '.claude-plugin', 'plugin.json'),
  join(SUBDIR, '.claude-plugin', 'plugin.json'),
];
const stale = targets.filter((t) => !existsSync(t) || readFileSync(t, 'utf8') !== serialized);
const links = { skills: '../../skills', agents: '../../agents' };
const badLinks = Object.entries(links).filter(([name, to]) => {
  const path = join(SUBDIR, name);
  return !existsSync(path) || !lstatSync(path).isSymbolicLink() || readlinkSync(path) !== to;
});

// `claude plugin tag` refuses to cut a release unless plugin.json and the
// enclosing marketplace entry agree on the version, so the marketplace copy of
// the number is generated here too rather than hand-maintained.
const marketPath = join(ROOT, '.claude-plugin', 'marketplace.json');
const market = JSON.parse(readFileSync(marketPath, 'utf8'));
const entry = market.plugins?.find((plugin) => plugin.name === manifest.name);
if (!entry) throw new Error(`marketplace.json has no entry named ${manifest.name}`);
entry.version = pkg.version;
const marketSerialized = `${JSON.stringify(market, null, 2)}\n`;
const marketCurrent = readFileSync(marketPath, 'utf8');

if (CHECK) {
  if (stale.length > 0) {
    console.error(`plugin.json is out of date (${stale.map((t) => relative(ROOT, t)).join(', ')}) — run: node scripts/build-plugin-manifest.mjs`);
    process.exit(1);
  }
  if (badLinks.length > 0) {
    console.error(`plugins/bdb-aos symlinks missing or wrong (${badLinks.map(([n]) => n).join(', ')}) — run: node scripts/build-plugin-manifest.mjs`);
    process.exit(1);
  }
  if (marketCurrent !== marketSerialized) {
    console.error('marketplace.json version is out of date — run: node scripts/build-plugin-manifest.mjs');
    process.exit(1);
  }
  if (drift.length > 0) {
    console.error(`agents/ is out of date (${drift.join(', ')}) — run: node scripts/build-plugin-manifest.mjs`);
    process.exit(1);
  }
  console.log(`plugin manifests up to date: ${skills.length} skills, ${agentNames.length} agents`);
} else {
  for (const t of targets) {
    mkdirSync(dirname(t), { recursive: true });
    writeFileSync(t, serialized);
  }
  for (const [name, to] of badLinks) {
    rmSync(join(SUBDIR, name), { force: true });
    symlinkSync(to, join(SUBDIR, name));
  }
  writeFileSync(marketPath, marketSerialized);
  console.log(`Wrote 2 plugin.json files with ${skills.length} skills and ${agentNames.length} agents`);
}
