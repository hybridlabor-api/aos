#!/usr/bin/env node
// Generates the agent-facing CLI reference from lib/cli-specs:
//   docs/cli-reference.md                         full reference, one section per CLI
//   AGENTS.md          <!-- aos:cli-reference -->  short "AOS CLIs for agents" block
//   skills/bdb-aos/SKILL.md <!-- aos:cli-table --> CLI table for the router skill
// Usage: node scripts/build-cli-reference.mjs [--check]   (--check writes nothing, exits 1 when a file is stale)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import SPECS from '../lib/cli-specs/index.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const flagName = (f) => (f.arg ? `${f.name} ${f.arg}` : f.name);
const first = (s) => s.examples?.[0] || s.usage[0];
const SAFETY = {
  yes: 'safe to call',
  caution: 'has side effects, call only when the task needs it',
  'human-only': 'human only, never call unprompted',
};

function section(s) {
  const out = [`## ${s.name}`, '', s.summary, '', `- **When to use:** ${s.whenToUse}`, `- **Agent safety:** ${SAFETY[s.agentSafe] || s.agentSafe}. ${s.sideEffects}`, `- **Entry:** \`${s.entry}\`${s.aliases?.length ? `; aliases: ${s.aliases.map((a) => `\`${a}\``).join(', ')}` : ''}`, '', '```text', ...s.usage, '```'];
  if (s.commands.length) out.push('', '| Command | Usage | What it does |', '|---|---|---|', ...s.commands.map((c) => `| \`${cell(c.name)}\` | \`${cell(c.usage)}\` | ${cell(c.summary)} |`));
  if (s.flags.length) out.push('', '| Option | What it does |', '|---|---|', ...s.flags.map((f) => `| \`${cell(flagName(f))}\` | ${cell(f.summary)} |`));
  if (s.env.length) out.push('', '| Environment | What it does |', '|---|---|', ...s.env.map((e) => `| \`${e.name}\` | ${cell(e.summary)} |`));
  out.push('', '| Exit code | Meaning |', '|---|---|', ...s.exit.map((e) => `| ${e.code} | ${cell(e.meaning)} |`));
  out.push('', `**JSON:** ${s.json}`);
  if (s.examples?.length) out.push('', '```sh', ...s.examples, '```');
  return out.join('\n');
}

export function referenceDoc() {
  return [
    '# AOS CLI reference',
    '',
    '<!-- Generated by scripts/build-cli-reference.mjs from lib/cli-specs. Do not edit by hand. -->',
    '',
    'Every AOS CLI answers `--help`, `-h` and `help` without side effects (exit 0). `aos help --all` lists them, `aos help --all --json` is the machine-readable form, `aos help <cli> --json` gives one spec.',
    '',
    '## Which CLI when',
    '',
    '| CLI | Use it to | First command |',
    '|---|---|---|',
    ...SPECS.map((s) => `| \`${s.name}\` | ${cell(s.whenToUse)} | \`${cell(first(s))}\` |`),
    '',
    ...SPECS.map(section).flatMap((x) => [x, '']),
  ].join('\n').replace(/\n+$/, '\n');
}

export function agentsBlock() {
  const humanOnly = SPECS.filter((s) => s.agentSafe === 'human-only').map((s) => `\`${s.name}\``);
  return [
    '## AOS CLIs for agents',
    '',
    'Probe before you guess: `aos help --all --json` lists every AOS CLI with usage, flags, exit codes and JSON support; `<cli> --help` is always side-effect free. Full reference: `docs/cli-reference.md`.',
    `Never call ${humanOnly.join(', ')} unprompted: they are for the human.`,
    '',
    ...SPECS.map((s) => `- \`${s.name}\` - ${s.whenToUse}${s.agentSafe === 'caution' ? ' (side effects)' : ''}`),
  ].join('\n');
}

export function skillTable() {
  return [
    '| CLI | Use it to | First command |',
    '|---|---|---|',
    ...SPECS.filter((s) => s.agentSafe !== 'human-only').map((s) => `| \`${s.name}\` | ${cell(s.whenToUse)} | \`${cell(first(s))}\` |`),
    '',
    'Probe with `aos help --all --json`; `<cli> --help` never has side effects.',
  ].join('\n');
}

const between = (text, tag, body, file) => {
  const start = `<!-- aos:${tag}:start -->`;
  const end = `<!-- aos:${tag}:end -->`;
  const s = text.indexOf(start);
  const e = text.indexOf(end);
  if (s < 0 || e < s) throw new Error(`${file}: markers ${start} ... ${end} not found`);
  return `${text.slice(0, s + start.length)}\n${body}\n${text.slice(e)}`;
};

export function buildOutputs(read = (f) => readFileSync(join(ROOT, f), 'utf8')) {
  return [
    { file: 'docs/cli-reference.md', content: referenceDoc() },
    { file: 'AGENTS.md', content: between(read('AGENTS.md'), 'cli-reference', agentsBlock(), 'AGENTS.md') },
    { file: 'skills/bdb-aos/SKILL.md', content: between(read('skills/bdb-aos/SKILL.md'), 'cli-table', skillTable(), 'skills/bdb-aos/SKILL.md') },
  ];
}

if (process.argv[1] && join(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const { file, content } of buildOutputs()) {
    let current = null;
    try { current = readFileSync(join(ROOT, file), 'utf8'); } catch { /* missing = stale */ }
    if (current === content) continue;
    stale++;
    if (check) console.error(`stale: ${file} (run node scripts/build-cli-reference.mjs)`);
    else { writeFileSync(join(ROOT, file), content); console.log(`wrote ${file}`); }
  }
  process.exit(check && stale ? 1 : 0);
}
