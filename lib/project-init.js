const fs = require('fs');
const path = require('path');
const { upsertDestructiveBlock } = require('./destructive-rules');

// Pointer files the doctor checks next to AGENTS.md.
const POINTER_FILES = ['CLAUDE.md', 'GEMINI.md', 'RULES.md', 'CODEX.md'];

function runProjectInit({ args = [], currentDir, srcDir, log, platform = process.platform }) {
    const force = args.includes('--force');

    const pAgents = path.join(currentDir, 'AGENTS.md');
    const pointers = POINTER_FILES.map((n) => path.join(currentDir, n));
    const aosDir = path.join(currentDir, '.aos');
    const evalsDir = path.join(aosDir, 'evals');
    const pProjectJson = path.join(aosDir, 'project.json');
    const pOpenwikiIgnore = path.join(currentDir, '.openwikiignore');

    const tmplPath = path.join(srcDir, 'skills', 'global_config', 'aos-project-init', 'assets', 'AGENTS.template.md');
    const tmplOpenwikiIgnore = path.join(srcDir, 'skills', 'global_config', 'aos-project-init', 'assets', 'openwikiignore.template');
    const projectName = path.basename(currentDir);

    let projectJsonConfig = {};
    if (fs.existsSync(pProjectJson)) {
        try {
            projectJsonConfig = JSON.parse(fs.readFileSync(pProjectJson, 'utf8'));
        } catch (e) {
            // ignore
        }
    }

    const plan = [];

    // Template with the project name filled in, plus the managed Destructive Actions block.
    const renderAgents = () => upsertDestructiveBlock((fs.existsSync(tmplPath) ? fs.readFileSync(tmplPath, 'utf8') : '# Agents').replace(/<PROJECT NAME>/g, projectName));

    const handleBackup = (filepath) => {
        if (force && fs.existsSync(filepath)) {
            const isSymlink = fs.lstatSync(filepath).isSymbolicLink();
            let shouldBackup = true;

            if (isSymlink) {
                const target = fs.readlinkSync(filepath);
                if (target === 'AGENTS.md') shouldBackup = false; // generated by us
            } else {
                const content = fs.readFileSync(filepath, 'utf8');
                if (content.includes('**See [AGENTS.md](AGENTS.md) for the definitive rules')) shouldBackup = false; // generated by us
                // For AGENTS.md, if we generated it from template, it might be hard to tell without a marker.
                // It's safer to just back it up if it exists, or maybe we assume they want to backup anything they hand-wrote.
                // Let's back up everything that exists and isn't our own generated symlink/pointer.
                if (filepath.endsWith('AGENTS.md') && content === renderAgents()) {
                    shouldBackup = false;
                }
            }

            if (shouldBackup) {
                const backupPath = `${filepath}.bak`;
                if (!isSymlink) {
                    fs.copyFileSync(filepath, backupPath);
                    plan.push(`Backed up ${filepath} to ${backupPath}`);
                }
            }
        }
    };

    if (!fs.existsSync(pAgents) || force) {
        plan.push(`Wrote ${pAgents}`);
    } else {
        plan.push(`Skipped ${pAgents} (already exists)`);
    }

    for (const pt of pointers) {
        if (!fs.existsSync(pt) || force) {
            plan.push(`Wrote ${pt} pointer to AGENTS.md`);
        } else {
            plan.push(`Skipped ${pt} (already exists)`);
        }
    }

    if (!fs.existsSync(aosDir)) {
        plan.push(`Created directory ${aosDir}`);
    }

    if (!fs.existsSync(evalsDir)) {
        plan.push(`Created directory ${evalsDir}`);
    }

    if (!fs.existsSync(pProjectJson) || force) {
        plan.push(`Wrote ${pProjectJson}`);
    } else {
        plan.push(`Skipped ${pProjectJson} (already exists)`);
    }

    // Written whenever missing: without it OpenWiki indexes dependencies and its own pages.
    // Skipped only when the project explicitly opted out of OpenWiki.
    const shouldWriteOpenWikiIgnore = force || !(projectJsonConfig.openwiki && projectJsonConfig.openwiki.enabled === false);

    if (shouldWriteOpenWikiIgnore) {
        if (!fs.existsSync(pOpenwikiIgnore) || force) {
            plan.push(`Wrote ${pOpenwikiIgnore}`);
        } else {
            plan.push(`Skipped ${pOpenwikiIgnore} (already exists)`);
        }
    }

    log.step('Project init plan:');
    for (const item of plan) {
        log.step(`  - ${item}`);
    }

    if (!fs.existsSync(pAgents) || force) {
        handleBackup(pAgents);
        fs.writeFileSync(pAgents, renderAgents());
    }

    for (const pt of pointers) {
        if (!fs.existsSync(pt) || force) {
            handleBackup(pt);
            if (fs.existsSync(pt)) fs.rmSync(pt, { force: true });

            if (platform === 'win32') {
                fs.writeFileSync(pt, '**See [AGENTS.md](AGENTS.md) for the definitive rules — they apply to all harnesses.**\n');
            } else {
                try {
                    fs.symlinkSync('AGENTS.md', pt);
                } catch (e) {
                    fs.writeFileSync(pt, '**See [AGENTS.md](AGENTS.md) for the definitive rules — they apply to all harnesses.**\n');
                }
            }
        }
    }

    if (!fs.existsSync(aosDir)) fs.mkdirSync(aosDir, { recursive: true });
    if (!fs.existsSync(evalsDir)) fs.mkdirSync(evalsDir, { recursive: true });

    if (!fs.existsSync(pProjectJson) || force) {
        const slug = projectName.toLowerCase().replace(/[^a-z0-9-]/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '') || 'project';
        const projectData = { name: projectName, slug };
        fs.writeFileSync(pProjectJson, JSON.stringify(projectData, null, 2) + '\n');
    }

    if (shouldWriteOpenWikiIgnore) {
        if (!fs.existsSync(pOpenwikiIgnore) || force) {
            const ignoreTemplate = fs.existsSync(tmplOpenwikiIgnore) ? fs.readFileSync(tmplOpenwikiIgnore, 'utf8') : '';
            fs.writeFileSync(pOpenwikiIgnore, ignoreTemplate);
        }
    }
}

module.exports = {
    runProjectInit
};
